"""The train / held-out split (``benchfea.bench.splits``, ``tasks.derived_seed``; docs/BENCHMARK.md section 7):

* the held-out (family, curve ball) pairs are the result of the written rule, nothing else;
* no base model can be generated for both splits: the generator seeds of the two splits are disjoint
  for every planned cell and every attempt of the derivation chain (no analysis needed), and the base
  models actually generated for the planned cells are different documents (generation needed: the
  cheap families by default, more with ``-m slow``, every planned cell with ``BENCHFEA_SPLIT_FULL=1``,
  about an hour).

None of this reads the built dataset under ``data/``.
"""
import hashlib
import json
import os
from pathlib import Path

import pytest

from benchfea.bench import curveballs, dataset, generate, splits
from benchfea.bench import tasks as T
from benchfea.bench.families import FAMILIES
from benchfea.bench.generate import GenerationFailed

from bench_helpers import CELLS

DOCS = Path(__file__).resolve().parents[1] / "docs"
FULL = bool(os.environ.get("BENCHFEA_SPLIT_FULL"))
#: (family, level) whose base models are generated by default / with the slow tests (seconds per model
#: measured: below 1 s / below 5 s); everything else only with BENCHFEA_SPLIT_FULL=1
QUICK = {("continuous_beam", 1), ("continuous_beam", 2)}
SLOW = {("continuous_beam", 3), ("portal_frame", 1), ("portal_frame", 2), ("portal_frame", 3), ("stair_frame", 1),
        ("stair_frame", 2), ("multistorey_2d", 2)}


# ------------------------------------------------------------------------------- selection rule
def test_held_out_combinations_are_the_result_of_the_written_rule():
    d = splits.load_splits()
    sel = d["heldOutSelection"]
    assert sel["perFamily"] == 2 and list(sel["applicable"]) == list(FAMILIES)
    assert d["heldOutCombinations"] == splits.select_held_out(sel["applicable"], sel["perFamily"])
    # the rule, written out once more without the module: smallest SHA-256 of the pair text
    for family, names in sel["applicable"].items():
        assert len(set(names)) == len(names) >= 2 and set(names) <= set(curveballs.available())
        ranked = sorted(names, key=lambda c: hashlib.sha256(
            f"benchfea.bench|held-out-pair|{family}|{c}".encode("utf-8")).hexdigest())
        assert [c for f, c in d["heldOutCombinations"] if f == family] == ranked[:2]
    assert len(d["heldOutCombinations"]) == 2 * len(FAMILIES)
    assert d["_heldOut"] == {tuple(p) for p in d["heldOutCombinations"]}


def _applicability_table():
    """{family: {curve ball: [effect classes]}} of the table of docs/CURVEBALLS.md section 5."""
    text = (DOCS / "CURVEBALLS.md").read_text(encoding="utf-8")
    section = text.split("## 5. Applicability", 1)[1].split("\n## ", 1)[0]
    rows = [[c.strip(" `") for c in line.strip().strip("|").split("|")]
            for line in section.splitlines() if line.startswith("|")]
    families = rows[0][1:]
    table = {f: {} for f in families}
    for row in rows[2:]:
        for f, cell in zip(families, row[1:]):
            if cell != "-":
                table[f][row[0]] = cell.split()
    return table


def test_applicable_pairs_of_the_split_file_are_those_of_the_applicability_table():
    """``heldOutSelection.applicable`` is the measured table, not a list of pairs somebody picked: every
    cell that is not '-' and not invalid-model alone ('I': never served, by definition)."""
    if not (DOCS / "CURVEBALLS.md").is_file():
        pytest.skip("docs/CURVEBALLS.md is not part of this installation")
    table = _applicability_table()
    assert set(table) == set(FAMILIES) and {c for row in table.values() for c in row} <= set(curveballs.available())
    expected = {f: [c for c, classes in row.items() if set(classes) - {"I"}] for f, row in table.items()}
    assert splits.load_splits()["heldOutSelection"]["applicable"] == expected
    assert ["diaphragm_frame", "constraint_wrong_slave"] not in splits.load_splits()["heldOutCombinations"]


def test_helper_cells_are_in_the_expected_split():
    for name in ("change", "mechanism", "design_only"):
        assert splits.split_of(*CELLS[name][:3]) == "train", name
    family, cb, seed, _ = CELLS["held_out_seed"]
    assert splits.is_held_out(family, cb, seed) and not splits.is_held_out(family, cb, 0)


# ------------------------------------------------------------------------- disjoint base models
def _planned_base_models(seeds=(0, 1, 4)):
    """{(family, level, generator seed): set of splits} over every planned cell and every attempt."""
    out = {}
    for family, cb, seed, level in dataset.plan(seeds=seeds):
        split = splits.split_of(family, cb, seed)
        for k in range(T.MAX_ATTEMPTS):
            out.setdefault((family, level, T.derived_seed(family, cb, seed, level, k)), set()).add(split)
    return out


def test_generator_seeds_of_the_two_splits_are_disjoint_for_every_planned_cell():
    """The base model (and the target of the curve ball) of an attempt is a function of (family, level,
    generator seed).  No such triple is used by both splits -- for the seeds of the committed dataset and
    for twenty more -- and the reason is structural: the lowest bit of the generator seed is the split."""
    for seeds in ((0, 1, 4), tuple(range(20))):
        planned = _planned_base_models(seeds)
        assert planned and all(len(s) == 1 for s in planned.values())
        by_split = {"train": set(), "held-out": set()}
        for (family, level, g), s in planned.items():
            (split,) = s
            assert 0 <= g < 2 ** 31 and g % 2 == (1 if split == "held-out" else 0)
            by_split[split].add((family, level, g))
        assert by_split["train"] and by_split["held-out"] and not by_split["train"] & by_split["held-out"]
    # the weakness this replaces: a held-out COMBINATION asked for with a train seed shared the base model
    # of the train tasks of that (family, seed, level)
    held = {tuple(p) for p in splits.load_splits()["heldOutCombinations"]}
    shared_before = 0
    for family, cb, seed, level in dataset.plan(seeds=(0, 1, 4)):
        if (family, cb) in held and seed % 5 != 4:
            train_cb = next(c for f, c in splits.combinations("train") if f == family)
            assert splits.split_of(family, train_cb, seed) == "train"
            for k in range(T.MAX_ATTEMPTS):
                assert T.derived_seed(family, cb, seed, level, k) != T.derived_seed(family, train_cb, seed, level, k)
            shared_before += 1
    assert shared_before


def _base_hash(family, level, gseed):
    """SHA-256 of the base model as ``tasks`` uses it (neutral name), or None when there is no model."""
    try:
        doc = dict(generate(family, gseed, level).document)
    except GenerationFailed:
        return None
    doc["name"] = f"{family.replace('_', ' ')} model"
    return hashlib.sha256(json.dumps(doc, sort_keys=True).encode("utf-8")).hexdigest()


def _check_documents(pairs):
    planned = {k: s for k, s in _planned_base_models().items() if FULL or (k[0], k[1]) in pairs}
    assert {s for v in planned.values() for s in v} == {"train", "held-out"}
    hashes = {"train": {}, "held-out": {}}
    for (family, level, g), s in sorted(planned.items()):
        (split,) = s
        h = _base_hash(family, level, g)
        if h is not None:
            hashes[split].setdefault(h, []).append((family, level, g))
    assert hashes["train"] and hashes["held-out"]
    both = set(hashes["train"]) & set(hashes["held-out"])
    assert not both, {h: (hashes["train"][h], hashes["held-out"][h]) for h in both}


def test_base_models_of_the_two_splits_are_different_documents():
    """Different generator seeds could still give the same document.  They do not: the base models of
    the planned cells (every attempt of the chain) have no SHA-256 in common between the splits."""
    _check_documents(QUICK)


@pytest.mark.slow
def test_base_models_of_the_two_splits_are_different_documents_more_families():
    _check_documents(QUICK | SLOW)
