"""The worked examples in ``examples/``: every file is valid, runs with all invariants passed, and
the numbers quoted in its explanation (``examples/<name>.md``, table "Key results") are the numbers
the engine produces now.

``QUANTITIES[name](model, results, design)`` -> ordered {label: (value, unit)} in the file's units;
``examples/expected.json`` holds the same values; the tables in the .md files are written from
``format_value`` of them (the example files and tables are regenerated by hand when an example
changes -- this test only checks that the three agree).

Independent of the stored numbers, the closed-form results that exist for an example are checked
directly (derived here from statics / the beam equation, stated in each test).
"""
import json
import math
from pathlib import Path

import numpy as np
import pytest

from benchfea import design as design_module
from benchfea.io import load
from benchfea.model import build_model
from benchfea.solve import analyze
from benchfea.validate import validate

EXAMPLES = Path(__file__).resolve().parents[1] / "examples"
NAMES = ["01_simple_beam", "02_continuous_beam", "03_portal_frame", "04_diaphragm_frame", "05_braced_frame"]
DOF = {"ux": 0, "uy": 1, "uz": 2, "rx": 3, "ry": 4, "rz": 5}


def format_value(value: float) -> str:
    """How a number is printed in the .md tables (4 significant digits)."""
    return f"{value:.4g}"


# ------------------------------------------------------------------------------------------ helpers
class Run:
    """An analysed example with accessors in FILE units."""

    def __init__(self, name: str):
        self.model = build_model(EXAMPLES / f"{name}.json")
        self.results = analyze(self.model)
        self.design = design_module.check(self.model, self.results)
        self.u = self.model.units

    def disp(self, combo, node, dof):
        v = self.results.combinations[combo].displacements[self.model.nodes[node].index, DOF[dof]]
        return float(self.u.from_internal(v, "length")) if DOF[dof] < 3 else float(v)

    def reaction(self, combo, node, dof):
        v = self.results.combinations[combo].reactions[self.model.nodes[node].index, DOF[dof]]
        return float(self.u.from_internal(v, "force" if DOF[dof] < 3 else "moment"))

    def force(self, combo, member, component, x=None, how=None):
        """Station force: at relative position ``x`` (nearest station), or ``how`` = "max" | "min" | "absmax"."""
        r = self.results.combinations[combo].members[member]
        k = ("N", "Vy", "Vz", "T", "My", "Mz").index(component)
        col = r.forces[:, k]
        if how == "max":
            v = col.max()
        elif how == "min":
            v = col.min()
        elif how == "absmax":
            v = col[np.abs(col).argmax()]
        else:
            v = col[int(np.abs(r.x - x * r.x[-1]).argmin())]
        return float(self.u.from_internal(v, "force" if k < 3 else "moment"))

    def deflection(self, combo, member, component="uy"):
        """Largest local deflection of the member axis (signed)."""
        r = self.results.combinations[combo].members[member]
        col = r.displacements[:, ("ux", "uy", "uz").index(component)]
        return float(self.u.from_internal(col[np.abs(col).argmax()], "length"))

    def ratio(self, member):
        return float(self.design.members[member].governing.ratio)

    def check(self, member, startswith):
        cs = [c for c in self.design.members[member].checks if c.name.startswith(startswith) and c.ratio is not None]
        return float(max(c.ratio for c in cs))

    def buckling(self, combo, mode=0):
        return float(self.results.buckling[combo].factors[mode])

    def slack(self, combo):
        return sorted(m for m, r in self.results.combinations[combo].members.items() if not r.active)


def q01(r: Run):
    F, L, M = r.u.label("force"), r.u.label("length"), r.u.label("moment")
    return {
        "ULS: vertical reaction at A": (r.reaction("ULS", "A", "uz"), F),
        "ULS: bending moment Mz at midspan": (r.force("ULS", "B1", "Mz", x=0.5), M),
        "ULS: shear force Vy at A": (r.force("ULS", "B1", "Vy", x=0.0), F),
        "SLS-L: midspan deflection (local y)": (r.deflection("SLS-L", "B1"), L),
        "SLS: midspan deflection (local y)": (r.deflection("SLS", "B1"), L),
        "design: flexure ratio (largest of the Chapter F checks)": (r.check("B1", "flexure"), "-"),
        "design: shear ratio": (r.check("B1", "shear"), "-"),
        "design: deflection limit 1 ratio (L/360, live)": (r.check("B1", "deflection limit 1"), "-"),
        "design: deflection limit 2 ratio (L/240, total)": (r.check("B1", "deflection limit 2"), "-"),
        "design: governing ratio": (r.ratio("B1"), "-"),
    }


