def test_example_01_against_the_closed_form(runs):
    """Simply supported beam, uniform load w, span L, no shear deformation (statics and the beam
    equation EI v'''' = w, derived here): R = wL/2, M = wL^2/8, deflection = 5 w L^4 / (384 EI)."""
    r = runs("01_simple_beam")
    L, w_uls, w_live = 8.0, 1.2 * 12 + 1.6 * 18, 18.0
    sec = r.model.sections["I-450x200x14x9"]
    EI = float(r.u.from_internal(r.model.materials["steel"].E * sec.props.Iz, "force*length^2"))
    q = q01(r)
    assert q["ULS: vertical reaction at A"][0] == pytest.approx(w_uls * L / 2, rel=1e-10)
    assert q["ULS: bending moment Mz at midspan"][0] == pytest.approx(w_uls * L ** 2 / 8, rel=1e-10)
    assert q["ULS: shear force Vy at A"][0] == pytest.approx(-w_uls * L / 2, rel=1e-10)
    assert q["SLS-L: midspan deflection (local y)"][0] == pytest.approx(-5 * w_live * L ** 4 / (384 * EI), rel=1e-10)
    # the deflection ratio is the deflection over L/360
    assert q["design: deflection limit 1 ratio (L/360, live)"][0] == pytest.approx(
        5 * w_live * L ** 4 / (384 * EI) / (L / 360), rel=1e-9)


def test_example_02_statics(runs):
    """Hinge: zero moment.  The drop-in part H-C is simply supported between the hinge and C, so its
    reactions follow from statics alone (derived here): with w on 270 in and P at its middle,
    R_C = R_H = w * 270 / 2 + P / 2.  B-H is a cantilever carrying R_H at its tip, so the moment
    over B is statically determinate, M_B = -(R_H * 90 + w * 90^2 / 2), and a settlement of B cannot
    change it.  Vertical equilibrium of the whole beam."""
    r = runs("02_continuous_beam")
    q = q02(r)
    assert abs(q["ULS1: bending moment Mz at the hinge H"][0]) < 1e-9 * abs(q["ULS1: bending moment Mz over support B"][0])
    sec = r.model.sections["I-24x9x0.8x0.5"]
    sw = float(r.u.from_internal(r.model.materials["steel"].unit_weight * sec.props.A, "force/length"))
    w = 1.2 * (0.1 + sw) + 1.6 * 0.15
    assert q["ULS1: vertical reaction at C"][0] == pytest.approx(w * 270 / 2 + 1.6 * 12 / 2, rel=1e-10)
    m_b = -((w * 270 / 2 + 1.6 * 12 / 2) * 90 + w * 90 ** 2 / 2)
    assert q["ULS1: bending moment Mz over support B"][0] == pytest.approx(m_b, rel=1e-10)
    assert q["ULS4 (with 0.5 in settlement of B): bending moment Mz over support B"][0] == pytest.approx(m_b, rel=1e-10)
    # ... but the settlement changes the statically indeterminate part: span 1 and its supports
    assert (q["ULS4 (with 0.5 in settlement of B): moment taken by the spring at A"][0]
            != pytest.approx(q["ULS1: moment taken by the rotational spring at A (reaction Mz)"][0], rel=1e-3))
    total = w * 648 + 1.6 * 12
    assert sum(q[f"ULS1: vertical reaction at {n}"][0] for n in "ABC") == pytest.approx(total, rel=1e-10)
    # spring: reaction moment = -k * rotation
    assert q["ULS1: moment taken by the rotational spring at A (reaction Mz)"][0] == pytest.approx(
        -400000 * q["ULS1: rotation of the beam end at A"][0], rel=1e-10)


def test_example_03_second_order_increases_the_sway(runs):
    q = q03(runs("03_portal_frame"))
    amp = q["sway amplification second order / first order"][0]
    assert 1.02 < amp < 1.5
    # a rough cross-check of the amplification with the buckling factor is NOT made: the buckling
    # factor belongs to ULS1 and the sway to ULS2
    assert q["buckling factor of ULS1, mode 1"][0] > 2.0


def test_example_04_floor_moves_as_a_rigid_body(runs):
    """Diaphragm kinematics (docs/CONVENTIONS.md section 5) with the vertical axis Y as normal:
    u_s = u_m + theta x (x_s - x_m) restricted to the plane: ux_s = ux_m + ry * dz, uz_s = uz_m - ry * dx.
    Statics: the base shears along X sum to the applied 20 kip (the reactions oppose the load)."""
    r = runs("04_diaphragm_frame")
    ux, uz, ry = (r.disp("SLS-X", "CM", d) for d in ("ux", "uz", "ry"))
    xm = r.model.nodes["CM"].xyz
    for n in ("A1", "B1", "C1", "D1"):
        d = (r.model.nodes[n].xyz - xm) / float(r.u.factor("length"))
        assert r.disp("SLS-X", n, "ux") == pytest.approx(ux + ry * d[2], rel=1e-9, abs=1e-12)
        assert r.disp("SLS-X", n, "uz") == pytest.approx(uz - ry * d[0], rel=1e-9, abs=1e-12)
        assert r.disp("SLS-X", n, "ry") == pytest.approx(ry, rel=1e-9, abs=1e-15)
    q = q04(r)
    shear = (q["SLS-X: base shear along X taken by columns CA + CB (line z = 0)"][0]
             + q["SLS-X: base shear along X taken by columns CD + CC (line z = 180)"][0])
    assert shear == pytest.approx(-20.0, rel=1e-9)
    assert abs(ry) > 0.0                                         # the eccentric load twists the floor
    # the load acts nearer to line z = 180 (CM at z = 108 of 180): that line takes the larger share
    assert abs(q["SLS-X: base shear along X taken by columns CD + CC (line z = 180)"][0]) > 10.0


def test_example_05_only_the_stretched_diagonals_work(runs):
    """Storey shear of the ground storey under ULS2 = 1.0 x (24 + 26 + 15) kN; the beams are pinned
    and the columns are pinned at the base and continuous, so the columns carry part of the shear
    only through continuity -- the working diagonal carries most of it.  Its tension is therefore
    below the statically determinate value V / cos(angle) and above half of it."""
    r = runs("05_braced_frame")
    assert r.slack("ULS2") == ["X1b", "X2b", "X3b"]
    assert r.slack("ULS3") == ["X1a", "X2a", "X3a"]
    t = q05(r)["ULS2 (wind from the left): tension in brace X1a"][0]
    diag = math.hypot(6.0, 4.0)
    upper = 65.0 * diag / 6.0
    assert 0.5 * upper < t <= upper * (1 + 1e-9)
    for combo in r.results.combinations:
        for m in r.slack(combo):
            # a slack diagonal takes no force from the frame: what is left is its own weight, carried to
            # its two ends (axial force antisymmetric about mid-length, never more than the weight)
            n = r.results.combinations[combo].members[m].forces[:, 0]
            weight = 1.2 * 77.0 * 7.04e-4 * 7.3 * 1000.0             # N, upper bound (factor, gamma, A, L)
            assert abs(n[len(n) // 2]) < 1e-9 * weight and np.abs(n).max() < weight
            assert n == pytest.approx(-n[::-1], abs=1e-9 * weight)
