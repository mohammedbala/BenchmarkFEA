QUANTITIES = {"01_simple_beam": q01, "02_continuous_beam": q02, "03_portal_frame": q03, "04_diaphragm_frame": q04,
              "05_braced_frame": q05}


@pytest.fixture(scope="module")
def runs():
    cache = {}

    def get(name):
        if name not in cache:
            cache[name] = Run(name)
        return cache[name]
    return get


# ------------------------------------------------------------------------------------------ tests
@pytest.mark.parametrize("name", NAMES)
def test_example_is_valid_with_no_warning(name):
    assert validate(load(EXAMPLES / f"{name}.json")) == []


@pytest.mark.parametrize("name", NAMES)
def test_example_runs_with_all_invariants_and_a_usable_design(name, runs):
    r = runs(name)
    assert set(r.results.combinations) == set(r.model.combinations)
    for cid, c in r.results.combinations.items():
        assert c.invariants.passed and c.converged, cid
    assert r.design.status in ("pass", "conditional")          # no failed and no blocked check
    for dm in r.design.members.values():
        assert dm.governing is not None and 0.0 < dm.governing.ratio <= 1.0
        assert dm.not_checked == []


@pytest.mark.parametrize("name", NAMES)
def test_documented_numbers_are_what_the_engine_gives(name, runs):
    expected = json.loads((EXAMPLES / "expected.json").read_text(encoding="utf-8"))[name]
    got = QUANTITIES[name](runs(name))
    assert list(got) == list(expected)
    text = (EXAMPLES / f"{name}.md").read_text(encoding="utf-8")
    for label, (value, unit) in got.items():
        ref = expected[label]["value"]
        assert value == pytest.approx(ref, rel=1e-6, abs=1e-9 * max(1.0, abs(ref))), label
        assert expected[label]["unit"] == unit
        row = f"| {label} | {format_value(ref)} | {unit} |"
        assert row in text, f"{name}.md does not quote: {row}"


